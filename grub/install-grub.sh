#!/usr/bin/env bash
# Dragon GRUB: install the glass theme and make sure Windows 11 shows up in the menu.
# Fedora, UEFI only. Run as root:   sudo ./grub/install-grub.sh [--dry-run] [--yes] [--uninstall]
#
# What it does (it is careful, because this is the bootloader):
#   1. Refuses to continue if the system is not UEFI, /boot/efi is not mounted, or this is not Fedora.
#   2. Warns if Secure Boot is on and shim is older than 16.1-7 (Windows chainloading failed on
#      Fedora 44 with older shim; the fix was a shim update).
#   3. Backs up /etc/default/grub, /boot/grub2/grub.cfg and your UEFI boot entries.
#   4. Installs the theme and adds ONE managed block to /etc/default/grub (easy to remove again).
#   5. Enables os-prober, builds the new grub.cfg to a temporary file, checks it, and only then
#      replaces the real one. If Windows is not found, it adds a direct chainload entry that
#      finds the Windows EFI partition by its UUID.
#   6. Prints, but does NOT run, the command to put Fedora first in the UEFI boot order.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
THEME_SRC="$HERE/theme/dragon"
GRUB_DIR="${DRAGON_GRUB_DIR:-/boot/grub2}"
DEFAULT_FILE="${DRAGON_GRUB_DEFAULT:-/etc/default/grub}"
GRUB_D="${DRAGON_GRUB_D:-/etc/grub.d}"
THEME_DST="$GRUB_DIR/themes/dragon"
WIN_ENTRY="$GRUB_D/41_dragon_windows"
STAMP="$(date +%Y%m%d-%H%M%S)"
BACKUP_DIR="/root/dragon-grub-backup-$STAMP"
ESP_GUID="c12a7328-f81f-11d2-ba4b-00a0c93ec93b"
MIN_SHIM="16.1-7"
DRY=0; YES=0; UNINSTALL=0

say()  { printf '\n\033[1;35m==> %s\033[0m\n' "$*"; }
warn() { printf '\033[1;33mWARNING: %s\033[0m\n' "$*" >&2; }
die()  { printf '\033[1;31mERROR: %s\033[0m\n' "$*" >&2; exit 1; }

run() {
    if [ "$DRY" -eq 1 ]; then printf '[dry-run] %s\n' "$*"; else "$@"; fi
}

ask() {
    [ "$YES" -eq 1 ] && return 0
    printf '%s [y/N] ' "$1" >&2
    read -r ans
    [ "$ans" = "y" ]
}

# true if version $1 >= $2 (sort -V ordering)
ver_ge() { [ "$(printf '%s\n%s\n' "$2" "$1" | sort -V | head -n1)" = "$2" ]; }

# Remove our block from /etc/default/grub (no-op if absent).
remove_block() {
    [ -f "$DEFAULT_FILE" ] || return 0
    run sed -i '/^# BEGIN dragon$/,/^# END dragon$/d' "$DEFAULT_FILE"
}

# Append our block. Later assignments win because grub2-mkconfig sources the file.
add_block() {
    local block
    block="$(cat <<EOF
# BEGIN dragon
# Managed by dragon/grub/install-grub.sh. Remove with: sudo ./grub/install-grub.sh --uninstall
GRUB_TERMINAL_OUTPUT="gfxterm"
GRUB_GFXMODE="1920x1080,auto"
GRUB_GFXPAYLOAD_LINUX="keep"
GRUB_THEME="$THEME_DST/theme.txt"
GRUB_TIMEOUT=8
GRUB_TIMEOUT_STYLE="menu"
GRUB_DEFAULT="saved"
GRUB_SAVEDEFAULT="true"
GRUB_DISABLE_OS_PROBER="false"
# END dragon
EOF
)"
    if [ "$DRY" -eq 1 ]; then
        printf '[dry-run] append to %s:\n%s\n' "$DEFAULT_FILE" "$block"
    else
        # make sure the file ends with a newline, then append (so remove_block restores it exactly)
        [ -z "$(tail -c1 "$DEFAULT_FILE")" ] || echo >> "$DEFAULT_FILE"
        printf '%s\n' "$block" >> "$DEFAULT_FILE"
    fi
}

# $1 = filesystem UUID of the EFI partition that holds Windows, $2 = out file
write_windows_entry() {
    local uuid="$1" out="$2"
    cat > "$out" <<EOF
#!/bin/sh
exec tail -n +3 \$0
# Generated by dragon/grub/install-grub.sh: chainload Windows from its own EFI partition.
if [ "\${grub_platform}" = "efi" ]; then
  menuentry 'Windows 11' --class windows --class os {
    savedefault
    insmod part_gpt
    insmod fat
    insmod chain
    search --no-floppy --fs-uuid --set=root $uuid
    chainloader /EFI/Microsoft/Boot/bootmgfw.efi
  }
fi
EOF
}

# Print "UUID" of an EFI System Partition that contains the Windows boot manager. Empty if none.
find_windows_esp() {
    local dev ptype fstype uuid mnt tmp="" found=""
    while read -r dev ptype fstype uuid; do
        [ "${ptype,,}" = "$ESP_GUID" ] && [ "$fstype" = "vfat" ] || continue
        mnt="$(findmnt -n -o TARGET -S "$dev" 2>/dev/null | head -n1 || true)"
        if [ -z "$mnt" ]; then
            tmp="$(mktemp -d)"
            mount -o ro "$dev" "$tmp" 2>/dev/null || { rmdir "$tmp"; continue; }
            mnt="$tmp"
        fi
        if [ -f "$mnt/EFI/Microsoft/Boot/bootmgfw.efi" ]; then found="$uuid"; fi
        if [ -n "$tmp" ]; then umount "$tmp" 2>/dev/null || true; rmdir "$tmp" 2>/dev/null || true; tmp=""; fi
        [ -n "$found" ] && break
    done < <(lsblk -rpno PATH,PARTTYPE,FSTYPE,UUID 2>/dev/null)
    printf '%s' "$found"
}

windows_in_cfg() { grep -qiE "menuentry '(Windows|Windows Boot Manager|Windows 11)" "$1"; }

preflight() {
    say "Pre-flight checks"
    [ "$(id -u)" -eq 0 ] || die "Run with sudo."
    [ -f /etc/fedora-release ] || die "This script is for Fedora."
    [ -d /sys/firmware/efi ] || die "This system booted in legacy/BIOS mode. GRUB cannot boot Windows 11 from a BIOS install. Reinstall Fedora in UEFI mode."
    findmnt -n -t vfat /boot/efi >/dev/null 2>&1 || die "/boot/efi is not mounted as the EFI System Partition. Fix /etc/fstab first (see: findmnt, lsblk -f)."
    [ -f "$GRUB_DIR/grub.cfg" ] || die "$GRUB_DIR/grub.cfg not found."
    [ -f "$THEME_SRC/theme.txt" ] || die "Theme files missing at $THEME_SRC."
    command -v grub2-mkconfig >/dev/null || die "grub2-mkconfig not found (install grub2-tools)."

    if command -v mokutil >/dev/null && mokutil --sb-state 2>/dev/null | grep -qi 'SecureBoot enabled'; then
        local shim
        shim="$(rpm -q --qf '%{VERSION}-%{RELEASE}' shim-x64 2>/dev/null | sed 's/\.fc[0-9].*//' || true)"
        echo "Secure Boot: enabled. shim-x64: ${shim:-unknown}"
        if [ -z "$shim" ] || ! ver_ge "$shim" "$MIN_SHIM"; then
            warn "shim is older than $MIN_SHIM. On Fedora 44 that broke 'Windows Boot Manager' from the GRUB menu with Secure Boot on."
            warn "Run:  sudo dnf upgrade --refresh   then re-run this script."
            ask "Continue anyway?" || exit 1
        fi
        if ! mokutil --db 2>/dev/null | grep -q 'Microsoft UEFI CA 2023'; then
            warn "Microsoft UEFI CA 2023 is not in the Secure Boot db yet (it arrives via fwupd / Windows Update). Windows may still boot, but check if it does not."
        fi
    else
        echo "Secure Boot: off or unknown."
    fi
}

do_uninstall() {
    say "Removing the Dragon GRUB theme and entries"
    remove_block
    run rm -f "$WIN_ENTRY"
    run rm -rf "$THEME_DST"
    run grub2-mkconfig -o "$GRUB_DIR/grub.cfg"
    echo "Done. Your backups (if any) are in /root/dragon-grub-backup-*."
}

do_install() {
    preflight

    say "Packages"
    run dnf install -y os-prober efibootmgr mokutil

    say "Backups -> $BACKUP_DIR"
    run mkdir -p "$BACKUP_DIR"
    run cp -a "$DEFAULT_FILE" "$BACKUP_DIR/default-grub"
    run cp -a "$GRUB_DIR/grub.cfg" "$BACKUP_DIR/grub.cfg"
    if [ "$DRY" -eq 0 ]; then efibootmgr -v > "$BACKUP_DIR/efibootmgr.txt" 2>&1 || true; fi

    say "Theme"
    run mkdir -p "$GRUB_DIR/themes"
    run rm -rf "$THEME_DST"
    run cp -r "$THEME_SRC" "$THEME_DST"

    say "Configuring $DEFAULT_FILE"
    remove_block
    add_block
    run grub2-editenv - unset menu_auto_hide

    say "What os-prober sees"
    os-prober 2>/dev/null || true

    if [ "$DRY" -eq 1 ]; then
        echo "[dry-run] would build $GRUB_DIR/grub.cfg.new, verify it, and replace $GRUB_DIR/grub.cfg"
        local u; u="$(find_windows_esp)"
        if [ -n "$u" ]; then echo "[dry-run] Windows EFI partition found (UUID $u)"; else echo "[dry-run] no Windows EFI partition found"; fi
        return 0
    fi

    say "Building grub.cfg (to a temporary file first)"
    rm -f "$WIN_ENTRY"
    local new="$GRUB_DIR/grub.cfg.new"
    if ! build_and_check "$new"; then
        warn "New config failed its checks. Restoring $DEFAULT_FILE and leaving grub.cfg untouched."
        cp -a "$BACKUP_DIR/default-grub" "$DEFAULT_FILE"; rm -f "$new"; exit 1
    fi

    if ! windows_in_cfg "$new"; then
        warn "os-prober did not add Windows. Looking for the Windows EFI partition directly..."
        local uuid; uuid="$(find_windows_esp)"
        if [ -n "$uuid" ]; then
            write_windows_entry "$uuid" "$WIN_ENTRY"; chmod 0755 "$WIN_ENTRY"
            echo "Windows boot manager found on EFI partition UUID $uuid; added $WIN_ENTRY"
            if ! build_and_check "$new" || ! windows_in_cfg "$new"; then
                warn "Config with the Windows entry failed its checks. Removing it and keeping the old grub.cfg."
                rm -f "$WIN_ENTRY" "$new"; cp -a "$BACKUP_DIR/default-grub" "$DEFAULT_FILE"; exit 1
            fi
        else
            warn "No Windows EFI partition found. Windows may be on another disk that is not connected, or not installed in UEFI mode."
            warn "The theme is installed; Windows will be added next time you re-run this script."
        fi
    fi

    mv -f "$new" "$GRUB_DIR/grub.cfg"
    echo "Installed $GRUB_DIR/grub.cfg"
    echo "Entries now in the menu:"; grep -E "^menuentry '" "$GRUB_DIR/grub.cfg" | sed "s/ --.*//" | sed 's/^/  /' || true

    boot_order_hint
    final_notes
}

# $1 = output file. Returns non-zero if the result looks wrong.
build_and_check() {
    local out="$1"
    grub2-mkconfig -o "$out" >/dev/null 2>&1 || return 1
    [ -s "$out" ] || return 1
    grep -q "theme" "$out" || return 1
    grep -qE "blscfg|menuentry" "$out" || return 1
    if command -v grub2-script-check >/dev/null; then grub2-script-check "$out" || return 1; fi
    return 0
}

boot_order_hint() {
    command -v efibootmgr >/dev/null || return 0
    local out fed win order rest new
    out="$(efibootmgr 2>/dev/null || true)"
    fed="$(printf '%s\n' "$out" | sed -n 's/^Boot\([0-9A-Fa-f]\{4\}\)\*\? Fedora.*/\1/p' | head -n1)"
    win="$(printf '%s\n' "$out" | sed -n 's/^Boot\([0-9A-Fa-f]\{4\}\)\*\? Windows Boot Manager.*/\1/p' | head -n1)"
    order="$(printf '%s\n' "$out" | sed -n 's/^BootOrder: //p')"
    [ -n "$fed" ] && [ -n "$order" ] || return 0
    rest="$(printf '%s' "$order" | tr ',' '\n' | grep -vx "$fed" | paste -sd, -)"
    new="$fed${rest:+,$rest}"
    say "UEFI boot order"
    echo "Current:  $order"
    echo "Fedora is Boot$fed${win:+, Windows Boot Manager is Boot$win}."
    if [ "${order%%,*}" != "$fed" ]; then
        echo "Windows Update can move itself to the front. To make Fedora (GRUB) first, run:"
        echo "  sudo efibootmgr -o $new"
    else
        echo "Fedora (GRUB) is already first. If a Windows update changes that later, run:"
        echo "  sudo efibootmgr -o $new"
    fi
}

final_notes() {
    cat <<EOF

Done. Backups: $BACKUP_DIR   (undo with: sudo $0 --uninstall)

Before you reboot, read these three:
  1. BitLocker / Device Encryption: if Windows 11 is encrypted, have your recovery key ready
     (https://account.microsoft.com/devices/recoverykey). Changes to the boot chain can ask for it.
  2. Windows Fast Startup: turn it off in Windows (Power options), or Linux can't safely read the NTFS disk.
  3. Clock: Windows and Linux disagree about the hardware clock. Easiest fix on Linux:
       sudo timedatectl set-local-rtc 1 --adjust-system-clock
EOF
}

main() {
    for a in "$@"; do
        case "$a" in
            --dry-run)   DRY=1 ;;
            --yes|-y)    YES=1 ;;
            --uninstall) UNINSTALL=1 ;;
            -h|--help)   sed -n '2,15p' "$0"; exit 0 ;;
            *) die "Unknown option: $a" ;;
        esac
    done
    if [ "$UNINSTALL" -eq 1 ]; then do_uninstall; else do_install; fi
}

if [ "${BASH_SOURCE[0]}" = "$0" ]; then main "$@"; fi
